"""
This module contains the theoretical formulas of the paper and the helpers to measure their inputs.
"""

import time

import torch
from transformers import PreTrainedModel

from .decoding import DecoderState, static_capacity
from .runner import ModelRunner


def synchronize(device: torch.device) -> None:
    """
    Wait for the queued device work to finish, so that wall clock timings are meaningful.
    """

    if device.type == "cuda":
        torch.cuda.synchronize(device)

    elif device.type == "mps":
        torch.mps.synchronize()


def expected_tokens_per_iteration(alpha: float, gamma: int) -> float:
    """
    Equation (1): the expected number of tokens generated by one run of Algorithm 1.
    """

    if alpha == 1:
        return gamma + 1
    return (1 - alpha ** (gamma + 1)) / (1 - alpha)


def expected_speedup(alpha: float, gamma: int, c: float) -> float:
    """
    Theorem 3.8: the expected walltime improvement, for the acceptance rate alpha and the cost coefficient c.
    """

    return expected_tokens_per_iteration(alpha, gamma) / (gamma * c + 1)


@torch.inference_mode()
def measure_cost_coefficient(
    target: PreTrainedModel | ModelRunner,
    draft: PreTrainedModel | ModelRunner,
    input_ids: torch.Tensor,
    use_cache: bool = True,
    repeats: int = 20,
    static_cache: bool = False,
) -> float:
    """
    Definition 3.7: the ratio between the time of a single run of the draft model and of the target model.

    Times one decoding step of each model on the same input, after the input is processed.
    """

    device: torch.device = input_ids.device

    def step_time(model: PreTrainedModel | ModelRunner) -> float:
        capacity: int | None = (
            static_capacity(model, input_ids, 2) if static_cache and not isinstance(model, ModelRunner) else None
        )
        state: DecoderState = DecoderState(model, input_ids, use_cache, capacity)
        state.logits()  # Process the input, which also warms up.
        length: int = len(state)
        synchronize(device)
        begin: float = time.perf_counter()
        for _ in range(repeats):
            state.extend([0])
            state.logits()
            state.truncate(length)
        synchronize(device)
        return (time.perf_counter() - begin) / repeats

    return step_time(draft) / step_time(target)
